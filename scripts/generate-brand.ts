/**
 * Generates every brand asset from one source of truth: the "rumi" wordmark set in
 * Inter Display Bold (opsz 32, wght 700) with tight, hand-tuned spacing.
 *
 *   npm run brand:generate
 *
 * Outputs
 *   src/components/brand/glyphs.ts      outlined SVG paths for the wordmark and the "r" mark
 *   src/app/icon.svg                    vector favicon
 *   src/app/favicon.ico                 16/32/48 px fallback favicon
 *   src/app/apple-icon.png              180 px home-screen icon (iOS)
 *   public/icons/icon-{192,512}.png     PWA icons
 *   public/icons/icon-maskable-512.png  PWA maskable icon (glyph inside the safe zone)
 *
 * scripts/assets/InterDisplay-Bold.ttf is a static instance of Inter (SIL OFL 1.1),
 * created with `fonttools varLib.instancer InterVariable.woff2 wght=700 opsz=32`.
 */
import fs from "node:fs";
import path from "node:path";
import * as fontkit from "fontkit";
import sharp from "sharp";

const ROOT = path.resolve(__dirname, "..");
const FONT_PATH = path.join(ROOT, "scripts/assets/InterDisplay-Bold.ttf");

const EMBER = "#E8542A";
const PAPER = "#FFF8F2";

/** Tracking in em, plus per-pair corrections so "r" never touches "u". */
const TRACKING = -0.06;
const PAIRS: Record<string, number> = { ru: 0.04, um: 0, mi: 0.01 };

const font = fontkit.openSync(FONT_PATH) as fontkit.Font;
const upm = font.unitsPerEm;

function round(n: number) {
  return Math.round(n * 100) / 100;
}

function wordmark() {
  const text = "rumi";
  const run = font.layout(text);
  let x = 0;
  const letters: string[] = [];
  let minY = Infinity;
  let maxY = -Infinity;
  run.glyphs.forEach((glyph, i) => {
    const pos = run.positions[i];
    const bbox = glyph.bbox;
    minY = Math.min(minY, bbox.minY);
    maxY = Math.max(maxY, bbox.maxY);
    letters.push(glyph.path.scale(1, -1).translate(x + pos.xOffset, 0).toSVG());
    const pair = text[i] + (text[i + 1] ?? "");
    const isLast = i === run.glyphs.length - 1;
    x += isLast ? bbox.maxX : pos.xAdvance + (TRACKING + (PAIRS[pair] ?? 0)) * upm;
  });
  const first = run.glyphs[0].bbox.minX;
  return {
    letters: letters.map((d) => shiftPath(d, -first, maxY)),
    width: round(x - first),
    height: round(maxY - minY),
  };
}

/** Re-bases a path so its top-left sits at (0, 0). */
function shiftPath(d: string, dx: number, top: number) {
  // fontkit emits absolute commands only (M, L, Q, C, Z) with space-separated
  // arguments, so every consecutive pair of numbers is one point.
  return d.replace(/([MLQCZ])([^MLQCZ]*)/g, (_, cmd: string, args: string) => {
    const nums = args.trim().split(/[\s,]+/).filter(Boolean).map(Number);
    const out: string[] = [];
    for (let i = 0; i + 1 < nums.length; i += 2) {
      out.push(`${round(nums[i] + dx)} ${round(nums[i + 1] + top)}`);
    }
    return cmd + out.join(" ");
  });
}

function letterR() {
  const glyph = font.glyphForCodePoint("r".codePointAt(0)!);
  const b = glyph.bbox;
  const d = shiftPath(glyph.path.scale(1, -1).toSVG(), -b.minX, b.maxY);
  return { d, width: round(b.maxX - b.minX), height: round(b.maxY - b.minY) };
}

const mark = wordmark();
const r = letterR();

function iconSvg(size: number, opts: { glyph: number; radius: number; nudge?: number }) {
  const scale = (size * opts.glyph) / r.height;
  const w = r.width * scale;
  const h = r.height * scale;
  const tx = (size - w) / 2 + size * (opts.nudge ?? 0.015);
  const ty = (size - h) / 2;
  const rx = round(size * opts.radius);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="${rx}" fill="${EMBER}"/><path transform="translate(${round(tx)} ${round(ty)}) scale(${scale.toFixed(5)})" d="${r.d}" fill="${PAPER}"/></svg>`;
}

async function png(svg: string, out: string) {
  await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(out);
}

/** Minimal ICO writer: a directory of embedded PNG images. */
function ico(images: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const dir = Buffer.alloc(16 * images.length);
  let offset = 6 + dir.length;
  images.forEach((img, i) => {
    const o = i * 16;
    dir.writeUInt8(img.size >= 256 ? 0 : img.size, o);
    dir.writeUInt8(img.size >= 256 ? 0 : img.size, o + 1);
    dir.writeUInt8(0, o + 2);
    dir.writeUInt8(0, o + 3);
    dir.writeUInt16LE(1, o + 4);
    dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(img.data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += img.data.length;
  });
  return Buffer.concat([header, dir, ...images.map((i) => i.data)]);
}

async function main() {
  const glyphsTs = `// Generated by scripts/generate-brand.ts — do not edit by hand.
// Inter Display Bold (SIL OFL 1.1), tracking ${TRACKING}em with tuned pairs.

export const WORDMARK = {
  width: ${mark.width},
  height: ${mark.height},
  /** One path per letter (r, u, m, i), already positioned, so letters can animate independently. */
  letters: [
${mark.letters.map((d) => `    "${d}",`).join("\n")}
  ],
} as const;

export const MARK_R = {
  width: ${r.width},
  height: ${r.height},
  d: "${r.d}",
} as const;
`;
  fs.writeFileSync(path.join(ROOT, "src/components/brand/glyphs.ts"), glyphsTs);

  fs.mkdirSync(path.join(ROOT, "public/icons"), { recursive: true });
  const app = path.join(ROOT, "src/app");

  fs.writeFileSync(path.join(app, "icon.svg"), iconSvg(64, { glyph: 0.56, radius: 0.22 }));
  await png(iconSvg(180, { glyph: 0.52, radius: 0 }), path.join(app, "apple-icon.png"));
  await png(iconSvg(192, { glyph: 0.52, radius: 0.22 }), path.join(ROOT, "public/icons/icon-192.png"));
  await png(iconSvg(512, { glyph: 0.52, radius: 0.22 }), path.join(ROOT, "public/icons/icon-512.png"));
  await png(
    iconSvg(512, { glyph: 0.4, radius: 0 }),
    path.join(ROOT, "public/icons/icon-maskable-512.png"),
  );

  const icoImages = await Promise.all(
    [16, 32, 48].map(async (size) => ({
      size,
      data: await sharp(Buffer.from(iconSvg(size, { glyph: 0.62, radius: 0.2 })))
        .png()
        .toBuffer(),
    })),
  );
  fs.writeFileSync(path.join(app, "favicon.ico"), ico(icoImages));

  console.log(`wordmark ${mark.width}×${mark.height} units, mark r ${r.width}×${r.height}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
